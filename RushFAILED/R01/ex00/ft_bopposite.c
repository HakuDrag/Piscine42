char	ft_bopposite(char **tab, int i, int j)
{
	if (i == 0)
		return (tab[1][j]);
	else if (i == 1)
		return (tab[0][j]);
	else if (i == 2)
		return (tab[3][j]);
	return (tab[2][j]);
}
